export const MESSAGES: Record<Language, Messages> = { de, en, zh, hi, es, fr };

/** "auto" picks the first supported system language; anything else falls back to English. */
export function resolveLanguage(setting: string, preferred: readonly string[] = navigator.languages): Language {
  if (setting in MESSAGES) return setting as Language;
  for (const tag of preferred) {
    const base = tag.toLowerCase().split('-')[0];
    if (base in MESSAGES) return base as Language;
  }
  return 'en';
}

const isAppError = (error: unknown): error is AppError =>
  typeof error === 'object' && error !== null && typeof (error as AppError).code === 'string';

/** Errors are kept untranslated in state, so switching the language re-renders them. */
export function describeError(t: Messages, error: unknown): string {
  if (isAppError(error)) {
    const text = (t.errors as Record<string, string>)[error.code] ?? t.errors.internal;
    return error.detail ? `${text}\n\n${t.details}: ${error.detail}` : text;
  }
  return error instanceof Error ? error.message : String(error);
}

